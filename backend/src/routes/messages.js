const express = require('express');
const router = express.Router();
const { pool } = require('../db');

router.get('/', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM messages ORDER BY created_at DESC');
    res.json(result.rows);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.get('/:id', async (req, res) => {
  try {
    const result = await pool.query('SELECT * FROM messages WHERE id = $1', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.post('/', async (req, res) => {
  try {
    const { sender_name, recipient_type, recipient_id, subject, body, status, read } = req.body;
    const result = await pool.query(
      `INSERT INTO messages (sender_name, recipient_type, recipient_id, subject, body, status, read)
       VALUES ($1,$2,$3,$4,$5,$6,$7) RETURNING *`,
      [sender_name, recipient_type, recipient_id, subject, body, status || 'Sent', read || false]
    );
    res.status(201).json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.put('/:id', async (req, res) => {
  try {
    const { sender_name, recipient_type, recipient_id, subject, body, status, read } = req.body;
    const result = await pool.query(
      `UPDATE messages SET sender_name=$1, recipient_type=$2, recipient_id=$3, subject=$4, body=$5, status=$6, read=$7
       WHERE id=$8 RETURNING *`,
      [sender_name, recipient_type, recipient_id, subject, body, status, read, req.params.id]
    );
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json(result.rows[0]);
  } catch (err) { res.status(500).json({ error: err.message }); }
});

router.delete('/:id', async (req, res) => {
  try {
    const result = await pool.query('DELETE FROM messages WHERE id = $1 RETURNING *', [req.params.id]);
    if (result.rows.length === 0) return res.status(404).json({ error: 'Not found' });
    res.json({ message: 'Deleted', item: result.rows[0] });
  } catch (err) { res.status(500).json({ error: err.message }); }
});

module.exports = router;
